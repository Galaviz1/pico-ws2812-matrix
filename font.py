_cache = {}


def glyph_columns(ch):
    """Column bitmasks for one character (unknown characters show as '?')."""
    if ch in _cache:
        return _cache[ch]
    rows = GLYPHS.get(ch, GLYPHS["?"]).split("/")
    width = max(len(r) for r in rows)
    cols = []
    for c in range(width):
        mask = 0
        for r, row in enumerate(rows):
            if c < len(row) and row[c] == "#":
                mask |= 1 << r
        cols.append(mask)
    _cache[ch] = cols
    return cols


def text_columns(text, gap=1):
    """Bitmask columns for a whole string, `gap` blank columns between glyphs."""
    out = []
    for i, ch in enumerate(text):
        if i:
            out.extend([0] * gap)
        out.extend(glyph_columns(ch))
    return out
